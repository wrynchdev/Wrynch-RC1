"""Write the component catalog as a Supabase migration from src/data/ontology.json.

Run after export_json.py:  python3 ontology/build/export_sql.py
"""
import json
import os

ROOT = os.path.join(os.path.dirname(__file__), "..", "..")
SRC = os.path.join(ROOT, "src", "data", "ontology.json")
OUT = os.path.join(ROOT, "supabase", "migrations", "20260926000100_catalog.sql")


def q(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, list):
        return "array[" + ", ".join(q(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


d = json.load(open(SRC))
lines = [f"-- Generated by ontology/build/export_sql.py from ontology v{d['version']}. Do not edit by hand.",
         "-- Upserts, so re-running after a catalog release updates labels and thresholds without touching history.", ""]

rows = [f"({c['id']}, {q(c['name'])}, {q(c['label'])}, {q(c['category'])}, {q(c['safety'])}, {q(c['aiPhoto'])}, {q(c['positionRule'])}, {q(c['positions'])})"
        for c in d["classes"]]
lines += ["insert into public.component_class (id, name, label, category, safety_critical, ai_photo, position_rule, allowed_positions) values",
          ",\n".join(rows),
          "on conflict (id) do update set name = excluded.name, label = excluded.label, category = excluded.category, safety_critical = excluded.safety_critical,",
          "  ai_photo = excluded.ai_photo, position_rule = excluded.position_rule, allowed_positions = excluded.allowed_positions;", ""]

rows = [f"({q(f['key'])}, {q(f['label'])}, {q(f['definition'])})" for f in d["findings"].values()]
lines += ["insert into public.finding_type (key, label, definition) values", ",\n".join(rows),
          "on conflict (key) do update set label = excluded.label, definition = excluded.definition;", ""]

rows = [f"({c['id']}, {q(k)}, {q(list(r))})" for c in d["classes"] for k, r in c["findings"].items()]
lines += ["insert into public.class_finding (class_id, finding_key, ratings) values", ",\n".join(rows),
          "on conflict (class_id, finding_key) do update set ratings = excluded.ratings;", ""]

rows = []
for ch in d["checks"].values():
    a = ch["auto"] or {}
    ok = a.get("ok") or [None, None]
    imm = a.get("immediate") or [None, None]
    rows.append(f"({q(ch['key'])}, {ch['classId']}, {q(ch['name'])}, {q(ch['unit'])}, {q(ch['valueType'])}, "
                f"{q(ok[0])}, {q(ok[1])}, {q(imm[0])}, {q(imm[1])})")
lines += ["insert into public.condition_check (key, class_id, name, unit, value_type, ok_op, ok_value, imm_op, imm_value) values",
          ",\n".join(rows),
          "on conflict (key) do update set class_id = excluded.class_id, name = excluded.name, unit = excluded.unit, value_type = excluded.value_type,",
          "  ok_op = excluded.ok_op, ok_value = excluded.ok_value, imm_op = excluded.imm_op, imm_value = excluded.imm_value;", ""]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, "w").write("\n".join(lines))
print("wrote", os.path.normpath(OUT), os.path.getsize(OUT), "bytes")

# ---------------------------------------------------------------- release migration
# The catalog file above loads a new database. A database that already ran it gets each catalog release from its own
# migration, written here: the same upserts, plus what a release removes and what the first file can't hold (the
# findings each check offers, and the order of a part's checks).
RELEASES = {"1.4.0": "20261016000000_catalog_v1_4_0.sql"}
if d["version"] in RELEASES:
    out = os.path.join(ROOT, "supabase", "migrations", RELEASES[d["version"]])
    r = [f"-- Generated by ontology/build/export_sql.py: catalog release v{d['version']}. Do not edit by hand.",
         "-- Brings a database loaded with an earlier catalog up to this one. Old results and findings keep their history.", "",
         "alter table public.condition_check",
         "  add column if not exists fail_findings text[] not null default '{}',",
         "  add column if not exists sort_order smallint not null default 0;",
         "comment on column public.condition_check.fail_findings is 'Findings this check offers (catalog). A finding is recorded under the check it explains.';",
         "comment on column public.condition_check.sort_order is 'Order of the check within its part (catalog). A confirmed AI finding goes under the first check that offers it.';", ""]
    r += lines  # classes, finding types, class findings, checks
    pairs = ", ".join(f"({c['id']}, {q(k)})" for c in d["classes"] for k in c["findings"])
    r += ["-- Findings a part can no longer have (findings already recorded keep their history).",
          f"delete from public.class_finding cf where (cf.class_id, cf.finding_key) not in (values {pairs});", ""]
    order = {}
    for c in d["classes"]:
        for i, k in enumerate(c["checks"]):
            order[k] = i
    rows = [f"({q(k)}, {q(ch['failFindings'])}, {order[k]})" for k, ch in d["checks"].items()]
    r += ["update public.condition_check c set fail_findings = v.fail_findings, sort_order = v.sort_order",
          "  from (values " + ",\n    ".join(rows) + ") v(key, fail_findings, sort_order) where c.key = v.key;", ""]
    keys = ", ".join(q(k) for k in d["checks"])
    r += ["-- Checks taken out of the catalog stay in condition_check for the results already recorded on them; switched off",
          "-- for every shop so nothing new is recorded on them.",
          "insert into public.platform_disabled_check (check_key, disabled_by)",
          f"select key, null from public.condition_check where key not in ({keys})",
          "on conflict (check_key) do nothing;", ""]
    open(out, "w").write("\n".join(r))
    print("wrote", os.path.normpath(out), os.path.getsize(out), "bytes")
